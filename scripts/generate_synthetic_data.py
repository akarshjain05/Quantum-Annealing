def generate_daily_demand(
    avg_volume: float,
    volatility: float,
    peak_multiplier: float,
    days: int = 90
) -> List[DailyDemand]:
    """
    Generate realistic daily demand patterns.
    
    Includes:
    - Weekly seasonality (higher Mon-Wed)
    - Monthly seasonality (higher end of month)
    - Random noise
    - Occasional spikes
    - Weekend reduction
    """
    demands = []
    base_date = datetime.now() - timedelta(days=days)
    
    for i in range(days):
        date = base_date + timedelta(days=i)
        day_of_week = date.weekday()
        day_of_month = date.day
        
        # Weekly seasonality
        if day_of_week < 3:  # Mon-Wed
            weekly_factor = 1.15
        elif day_of_week < 5:  # Thu-Fri
            weekly_factor = 0.95
        else:  # Weekend
            weekly_factor = 0.25  # Much lower on weekends
        
        # Monthly seasonality (higher end of month - salary payments, etc.)
        is_month_end = day_of_month > 25 or day_of_month < 5
        if is_month_end:
            monthly_factor = 1.25
        elif 10 <= day_of_month <= 15:  # Mid-month bump
            monthly_factor = 1.1
        else:
            monthly_factor = 1.0
        
        # Random noise
        if NUMPY_AVAILABLE:
            noise = np.random.normal(1.0, volatility)
        else:
            noise = 1.0 + random.gauss(0, volatility)
        noise = max(0.3, min(2.0, noise))  # Clamp
        
        # Occasional spikes (5% chance)
        is_spike = random.random() < 0.05
        spike_factor = random.uniform(peak_multiplier * 0.8, peak_multiplier) if is_spike else 1.0
        
        # Calculate demand
        demand = avg_volume * weekly_factor * monthly_factor * noise * spike_factor
        demand = max(0, demand)
        
        # Settlement split (90-95% settled same day)
        settlement_rate = random.uniform(0.90, 0.98)
        settled = demand * settlement_rate
        pending = demand - settled
        
        # Number of transactions (rough estimate)
        avg_transaction = random.uniform(50000, 200000)
        num_transactions = max(1, int(demand / avg_transaction))
        
        # Peak hour volume (typically 30-50% of daily in peak 2 hours)
        peak_hour_volume = demand * random.uniform(0.30, 0.50)
        
        demands.append(DailyDemand(
            date=date.strftime("%Y-%m-%d"),
            amount=round(demand, 2),
            settled_amount=round(settled, 2),
            pending_amount=round(pending, 2),
            num_transactions=num_transactions,
            peak_hour_volume=round(peak_hour_volume, 2),
            is_month_end=is_month_end,
            is_spike=is_spike
        ))
    
    return demands


def calculate_statistics(demands: List[DailyDemand]) -> Dict[str, float]:
    """Calculate statistical measures from demand history."""
    amounts = [d.amount for d in demands]
    
    if NUMPY_AVAILABLE:
        return {
            "avg_daily_volume": float(np.mean(amounts)),
            "median_daily_volume": float(np.median(amounts)),
            "std_daily_volume": float(np.std(amounts)),
            "min_daily_volume": float(np.min(amounts)),
            "max_daily_volume": float(np.max(amounts)),
            "p90_demand": float(np.percentile(amounts, 90)),
            "p95_demand": float(np.percentile(amounts, 95)),
            "p99_demand": float(np.percentile(amounts, 99)),
            "volatility": float(np.std(amounts) / np.mean(amounts)) if np.mean(amounts) > 0 else 0,
            "total_volume_90d": float(np.sum(amounts)),
            "spike_count": sum(1 for d in demands if d.is_spike),
            "weekend_avg": float(np.mean([d.amount for d in demands if datetime.strptime(d.date, "%Y-%m-%d").weekday() >= 5])) if any(datetime.strptime(d.date, "%Y-%m-%d").weekday() >= 5 for d in demands) else 0
        }
    else:
        sorted_amounts = sorted(amounts)
        n = len(amounts)
        mean_val = sum(amounts) / n
        variance = sum((x - mean_val) ** 2 for x in amounts) / n
        std_val = math.sqrt(variance)
        
        return {
            "avg_daily_volume": mean_val,
            "median_daily_volume": sorted_amounts[n // 2],
            "std_daily_volume": std_val,
            "min_daily_volume": min(amounts),
            "max_daily_volume": max(amounts),
            "p90_demand": sorted_amounts[int(n * 0.90)],
            "p95_demand": sorted_amounts[int(n * 0.95)],
            "p99_demand": sorted_amounts[int(n * 0.99)],
            "volatility": std_val / mean_val if mean_val > 0 else 0,
            "total_volume_90d": sum(amounts),
            "spike_count": sum(1 for d in demands if d.is_spike),
            "weekend_avg": 0
        }


def calculate_minimum_required(
    statistics: Dict[str, float],
    confidence_level: float = 0.95,
    safety_buffer: float = 0.05,
    fx_volatility: float = 0.02,
    correspondent_risk: float = 0.02
) -> Tuple[float, Dict[str, float]]:
    """
    Calculate minimum required balance with breakdown.
    
    Components:
    1. Base demand coverage (percentile-based)
    2. Safety buffer
    3. FX volatility reserve
    4. Correspondent risk margin
    """
    # Select percentile based on confidence level
    if confidence_level >= 0.99:
        base_demand = statistics["p99_demand"]
    elif confidence_level >= 0.95:
        base_demand = statistics["p95_demand"]
    else:
        base_demand = statistics["p90_demand"]
    
    # Calculate components
    safety_amount = base_demand * safety_buffer
    fx_reserve = base_demand * fx_volatility
    correspondent_margin = base_demand * correspondent_risk
    
    total = base_demand + safety_amount + fx_reserve + correspondent_margin
    
    breakdown = {
        "base_demand_coverage": round(base_demand, 2),
        "safety_buffer": round(safety_amount, 2),
        "fx_volatility_reserve": round(fx_reserve, 2),
        "correspondent_risk_margin": round(correspondent_margin, 2),
        "total_minimum_required": round(total, 2)
    }
    
    return total, breakdown


def generate_corridor(config: Dict[str, Any], corridor_id: int) -> Corridor:
    """Generate complete corridor data."""
    source = config["source"]
    dest = config["dest"]
    code = f"{source}_{dest}"
    
    # Select correspondent bank
    correspondents = CORRESPONDENT_BANKS.get(dest, CORRESPONDENT_BANKS["USD"])
    correspondent_data = random.choice(correspondents)
    
    correspondent = {
        "name": correspondent_data["name"],
        "swift_code": correspondent_data["swift"],
        "city": correspondent_data["city"],
        "country": get_country_for_currency(dest),
        "risk_rating": correspondent_data["rating"],
        "account_number": generate_account_number()
    }
    
    # Settlement window
    start_hour, end_hour = config["settlement_hours"]
    settlement_window = {
        "start_time": f"{start_hour:02d}:00",
        "end_time": f"{end_hour:02d}:00",
        "cutoff_time": f"{config['cutoff_hour']:02d}:00",
        "timezone": "UTC"
    }
    
    # Generate demand history
    demands = generate_daily_demand(
        avg_volume=config["avg_daily_volume"],
        volatility=config["volatility"],
        peak_multiplier=config["peak_multiplier"],
        days=90
    )
    
    # Calculate statistics
    statistics = calculate_statistics(demands)
    
    # Determine correspondent risk based on rating
    rating_risk_map = {"A+": 0.01, "A": 0.02, "A-": 0.03, "B+": 0.04, "B": 0.05}
    correspondent_risk = rating_risk_map.get(correspondent_data["rating"], 0.03)
    
    # Calculate minimum required
    minimum_required, breakdown = calculate_minimum_required(
        statistics=statistics,
        confidence_level=0.95,
        safety_buffer=0.05,
        fx_volatility=config["volatility"] * 0.5,  # Half of price volatility
        correspondent_risk=correspondent_risk
    )
    
    # Current balance (over-provisioned by 15-40%)
    over_provision = random.uniform(1.15, 1.40)
    current_balance = minimum_required * over_provision
    
    # Recommended balance (5% above minimum)
    recommended_balance = minimum_required * 1.05
    
    # Local currency balance
    fx_rate = BASE_FX_RATES.get(code, 1.0)
    current_balance_local = current_balance * fx_rate
    
    # Configuration
    corridor_config = {
        "confidence_level": 0.95,
        "safety_buffer_percent": 0.05,
        "fx_volatility_window_days": 30,
        "correspondent_risk_margin": correspondent_risk,
        "manual_floor": None,
        "is_locked": False,
        "auto_optimize": True,
        "alert_threshold_percent": 0.10
    }
    
    # Add breakdown to statistics
    statistics.update({
        "minimum_breakdown": breakdown,
        "over_provision_ratio": round(current_balance / minimum_required, 2),
        "excess_capital": round(current_balance - minimum_required, 2),
        "annual_opportunity_cost": round((current_balance - recommended_balance) * 0.05, 2)
    })
    
    return Corridor(
        id=f"corridor_{corridor_id}",
        code=code,
        name=f"{source} → {dest}",
        source_currency=source,
        destination_currency=dest,
        correspondent=correspondent,
        settlement_window=settlement_window,
        current_balance=round(current_balance, 2),
        current_balance_local=round(current_balance_local, 2),
        minimum_required=round(minimum_required, 2),
        recommended_balance=round(recommended_balance, 2),
        statistics=statistics,
        config=corridor_config,
        demand_history=[asdict(d) for d in demands],
        created_at=datetime.utcnow().isoformat(),
        synthetic=True
    )


