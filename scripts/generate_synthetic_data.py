    if verbose:
        print(f"   ✓ Generated {len(audit_records)} audit records")
    
    # 6. Save summary
    summary_file = output_dir / "data_summary.json"
    with open(summary_file, "w") as f:
        json.dump(summary, f, indent=2)
    
    # Calculate totals
    total_liquidity = sum(c.current_balance for c in corridors)
