def generate_transactions(
    corridors: List[Corridor],
    days: int = 7,
    transactions_per_day: int = 50
) -> List[Dict[str, Any]]:
    """Generate synthetic transaction records."""
    transactions = []
    base_date = datetime.now() - timedelta(days=days)
    
    transaction_types = ["PAYMENT", "RECEIPT", "TRANSFER", "SETTLEMENT"]
    statuses = ["COMPLETED", "PENDING", "PROCESSING"]
    
    for day in range(days):
        current_date = base_date + timedelta(days=day)
        
        # Skip weekends (fewer transactions)
        if current_date.weekday() >= 5:
            num_transactions = transactions_per_day // 5
        else:
            num_transactions = transactions_per_day
        
        for _ in range(num_transactions):
            corridor = random.choice(corridors)
            
            # Random time during business hours
            hour = random.randint(
                int(corridor.settlement_window["start_time"].split(":")[0]),
                int(corridor.settlement_window["end_time"].split(":")[0]) - 1
            )
            minute = random.randint(0, 59)
            second = random.randint(0, 59)
            
            timestamp = current_date.replace(hour=hour, minute=minute, second=second)
            
            # Transaction amount (log-normal distribution for realistic heavy tail)
            if NUMPY_AVAILABLE:
                amount = np.random.lognormal(mean=12, sigma=1.5)
            else:
                amount = random.lognormvariate(12, 1.5)
            amount = min(amount, 50_000_000)  # Cap at 50M
            
            # Generate transaction ID
            tx_id = f"TX{timestamp.strftime('%Y%m%d')}{random.randint(100000, 999999)}"
            
            # Reference
            if FAKER_AVAILABLE:
                reference = fake.bothify(text="REF-????-######")
                counterparty = fake.company()
            else:
                reference = f"REF-{random.randint(1000, 9999)}-{random.randint(100000, 999999)}"
                counterparty = f"Company {random.randint(1, 1000)}"
            
            transactions.append({
                "transaction_id": tx_id,
                "corridor_id": corridor.id,
                "corridor_code": corridor.code,
                "type": random.choice(transaction_types),
                "status": random.choices(statuses, weights=[0.85, 0.10, 0.05])[0],
                "amount": round(amount, 2),
                "currency": corridor.source_currency,
                "local_amount": round(amount * BASE_FX_RATES.get(corridor.code, 1.0), 2),
                "local_currency": corridor.destination_currency,
                "counterparty": counterparty,
                "reference": reference,
                "timestamp": timestamp.isoformat(),
                "settlement_date": (timestamp + timedelta(days=random.choice([0, 1]))).strftime("%Y-%m-%d"),
                "synthetic": True
            })
    
    # Sort by timestamp
    transactions.sort(key=lambda x: x["timestamp"])
    
    return transactions


def generate_audit_trail(num_records: int = 50) -> List[Dict[str, Any]]:
    """Generate synthetic audit trail records."""
    records = []
    base_date = datetime.now() - timedelta(days=30)
    
    event_types = [
        ("optimization_started", "System"),
        ("optimization_completed", "System"),
        ("approval_submitted", "A. Patel"),
        ("approval_decided", "J. Smith"),
        ("config_changed", "J. Smith"),
        ("data_refresh", "System"),
        ("user_login", "Various"),
        ("report_generated", "R. Sharma"),
    ]
    
    previous_hash = "0" * 64  # Genesis block
    
    for i in range(num_records):
        # Random timestamp
        days_ago = random.randint(0, 30)
        hours_ago = random.randint(0, 23)
        timestamp = base_date + timedelta(days=days_ago, hours=hours_ago)
        
        event_type, default_actor = random.choice(event_types)
        
        record = {
            "id": f"audit_{i:04d}",
            "timestamp": timestamp.isoformat(),
            "event_type": event_type,
            "actor": default_actor,
            "summary": generate_audit_summary(event_type),
            "details": {},
            "previous_hash": previous_hash
        }
        
        # Calculate hash
        record_data = json.dumps(record, sort_keys=True)
        record["hash"] = hashlib.sha256(record_data.encode()).hexdigest()
        previous_hash = record["hash"]
        
        records.append(record)
    
    # Sort by timestamp
    records.sort(key=lambda x: x["timestamp"])
    
    return records


def generate_audit_summary(event_type: str) -> str:
    """Generate human-readable audit summary."""
    summaries = {
        "optimization_started": "Optimization run initiated",
        "optimization_completed": f"Optimization completed successfully, {random.randint(5, 15)} corridors processed",
        "approval_submitted": "Optimization results submitted for approval",
        "approval_decided": random.choice(["Optimization approved", "Optimization rejected - market volatility"]),
        "config_changed": "Risk parameters updated",
        "data_refresh": "Daily corridor data refresh completed",
        "user_login": "User authenticated successfully",
        "report_generated": "Monthly treasury report generated",
    }
    return summaries.get(event_type, "Event recorded")


