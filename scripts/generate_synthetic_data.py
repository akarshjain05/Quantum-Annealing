def generate_all_data(output_dir: Path, verbose: bool = True) -> Dict[str, Any]:
    """Generate all synthetic data files."""
    output_dir.mkdir(parents=True, exist_ok=True)
    
    summary = {
        "generated_at": datetime.utcnow().isoformat(),
        "seed": RANDOM_SEED,
        "files": []
    }
    
