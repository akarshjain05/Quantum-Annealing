    with open(fx_file, "w") as f:
        json.dump(fx_rates, f, indent=2)
    
    summary["files"].append({"name": "fx_rates.json", "records": len(fx_rates)})
    
    if verbose:
        print(f"   ✓ Generated {len(fx_rates)} FX rates")
    
